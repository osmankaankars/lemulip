"use strict";
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');
const search = require('../site/catalog-search.js');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../site/catalog.js'),'utf8'),context);
const data = JSON.parse(JSON.stringify(context.window.LEMULIP_CATALOG));
const ids = q => search.filter(data,q).families.map(f=>f.id);
assert.equal(ids('').length,9);
assert.deepEqual(ids('  CrOp  '),['images','video']);
assert.deepEqual(ids('trim'),['audio','video']);
assert.ok(ids('Excel').includes('spreadsheets'));
assert.ok(ids('WEBP').includes('images'));
assert.deepEqual(ids('<script>alert(1)</script>'),[]);
assert.deepEqual(ids('no-such-file-type'),[]);
assert.deepEqual(ids('   '),ids(''));
assert.equal(search.filter(data,'crop').tools.length,2);
assert.equal(search.filter(data,'Copy Path').actions.length,1);
assert.equal(search.filter(data,'').tools.length,26);
assert.equal(search.filter(data,'').actions.length,6);
assert.equal(search.normalize('İMAGE'), 'image');
console.log('Catalog search: 12 assertions passed');
